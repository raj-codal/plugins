#!/usr/bin/env node
/**
 * Writes a `*.module.css.d.ts` next to every CSS module, typed with the exact names Lightning CSS
 * exports for it: the parser and CSS modules defaults `@tsdown/css` builds with. The names are
 * the authored ones whatever `modules.generateScopedName` a build sets (the pattern only shapes
 * the hashed values), so only a `localsConvention` would have to be mirrored here. TypeScript
 * picks the file up for `import styles from './X.module.css'`, so `oxlint`'s `typeCheck` reports
 * a misspelled class as TS2551 ("Did you mean …?").
 *
 * A file Lightning CSS cannot parse fails the run, as it would fail the build.
 *
 * `--check` writes nothing and fails when a typings file is missing, stale or orphaned.
 */
import {existsSync, globSync, readFileSync, rmSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {styleText} from 'node:util'

import {transform} from 'lightningcss'

const check = process.argv.includes('--check')
// The repository root: this file is `scripts/css-modules-types/src/index.ts`
const root = path.resolve(import.meta.dirname, '../../..')
const exclude = (file: string) =>
  /(?:^|\/)(?:node_modules|dist|storybook-static)(?:\/|$)/.test(file)
const identifier = /^[A-Za-z_$][\w$]*$/

function typingsFor(file: string, names: string[]): string {
  // oxfmt's `quoteProps: 'consistent'`: quote every key once one needs it
  const quote = names.some((name) => !identifier.test(name))
  const keys = names.map((name) =>
    quote ? `'${name.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'` : name,
  )
  const type = keys.length
    ? `{\n${keys.map((key) => `  readonly ${key}: string`).join('\n')}\n}`
    : 'Record<never, never>'
  return `// Generated by \`pnpm css:types\` from ${path.basename(file)}, do not edit\ndeclare const styles: ${type}\nexport default styles\n`
}

function report(file: string, line: number, column: number, message: string) {
  if (process.env['GITHUB_ACTIONS']) {
    console.error(`::error file=${file},line=${line},col=${column}::${message}`)
  }
  console.error(`${styleText('bold', `${file}:${line}:${column}`)} ${styleText('red', message)}`)
}

// Lightning CSS throws plain `Error`s with an untyped `loc: {line, column}`
function locationOf(error: unknown): [line: number, column: number] {
  const loc: unknown = error instanceof Error && 'loc' in error ? error.loc : undefined
  if (typeof loc === 'object' && loc !== null && 'line' in loc && 'column' in loc) {
    return [Number(loc.line), Number(loc.column)]
  }
  return [1, 1]
}

let failed = false
const modules = globSync('**/*.module.css', {cwd: root, exclude}).sort()

for (const file of modules) {
  const code = readFileSync(path.join(root, file))
  let names: string[]
  try {
    const {exports} = transform({filename: file, code, cssModules: true})
    names = Object.keys(exports ?? {}).sort()
  } catch (error) {
    failed = true
    report(file, ...locationOf(error), `Lightning CSS: ${String(error)}`)
    continue
  }

  const typingsFile = path.join(root, `${file}.d.ts`)
  const typings = typingsFor(file, names)
  const exists = existsSync(typingsFile)
  if (exists && readFileSync(typingsFile, 'utf8') === typings) continue
  if (check) {
    failed = true
    const problem = exists ? `Out of date with ${path.basename(file)}` : 'Missing'
    report(`${file}.d.ts`, 1, 1, `${problem}, run \`pnpm css:types\``)
  } else {
    writeFileSync(typingsFile, typings)
    process.stdout.write(`Wrote ${file}.d.ts\n`)
  }
}

for (const typingsFile of globSync('**/*.module.css.d.ts', {cwd: root, exclude})) {
  if (existsSync(path.join(root, typingsFile.slice(0, -'.d.ts'.length)))) continue
  if (check) {
    failed = true
    report(typingsFile, 1, 1, 'Its CSS module no longer exists, run `pnpm css:types`')
  } else {
    rmSync(path.join(root, typingsFile))
    process.stdout.write(`Removed ${typingsFile}\n`)
  }
}

if (failed) process.exitCode = 1
